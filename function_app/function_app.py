"""Process queued BlobCreated events and extract text from uploaded PDFs."""

from __future__ import annotations

import io
import json
import logging
import os
import re
from enum import Enum
from typing import Any, NamedTuple
from urllib.parse import unquote

import azure.functions as func
from azure.core import MatchConditions
from azure.core.exceptions import ResourceModifiedError
from azure.data.tables import TableClient, UpdateMode
from azure.storage.blob import BlobServiceClient
from pypdf import PdfReader

logger = logging.getLogger(__name__)

AZURE_WEBJOBS_STORAGE = "AzureWebJobsStorage"
UPLOAD_CONTAINER = os.getenv("UPLOAD_CONTAINER", "uploads")
EXTRACTED_CONTAINER = os.getenv("EXTRACTED_CONTAINER", "extracted")
TABLE_NAME = os.getenv("TABLE_NAME", "filestatus")
PARTITION_KEY = "pdf"
PDF_EXTENSION = ".pdf"
MAX_ERROR_LENGTH = 512
MAX_CLAIM_ATTEMPTS = 3
SUBJECT_PATTERN = re.compile(
    r"^/blobServices/default/containers/(?P<container>[^/]+)/blobs/(?P<blob_name>.+)$"
)

app = func.FunctionApp()


class Status(str, Enum):
    """Define supported PDF processing lifecycle values."""

    UPLOADED = "Uploaded"
    PROCESSING = "Processing"
    COMPLETED = "Completed"
    FAILED = "Failed"


class StorageClients(NamedTuple):
    """Group shared Blob and Table clients for reuse by every invocation."""

    blobs: BlobServiceClient
    table: TableClient


def _create_storage_clients() -> StorageClients:
    """Create shared SDK clients from the Functions host connection string.

    Returns:
        Blob and Table clients configured for the same storage account.

    Raises:
        RuntimeError: If AzureWebJobsStorage is missing, empty, or invalid.
    """
    connection_string = os.getenv(AZURE_WEBJOBS_STORAGE)
    if connection_string is None or not connection_string.strip():
        raise RuntimeError(
            "AzureWebJobsStorage is required and must contain a storage connection string"
        )

    try:
        return StorageClients(
            blobs=BlobServiceClient.from_connection_string(connection_string),
            table=TableClient.from_connection_string(
                conn_str=connection_string,
                table_name=TABLE_NAME,
            ),
        )
    except (TypeError, ValueError):
        raise RuntimeError("AzureWebJobsStorage is invalid") from None


def _parse_event(message_body: bytes) -> dict[str, Any]:
    """Parse one Event Grid event from a queue message.

    Args:
        message_body: Plain UTF-8 JSON bytes supplied by the queue trigger.

    Returns:
        Event Grid event object, unwrapped from a one-item array when needed.

    Raises:
        UnicodeDecodeError: If the message is not UTF-8 encoded.
        json.JSONDecodeError: If the message does not contain valid JSON.
        ValueError: If the JSON shape is not exactly one event object.
    """
    payload: Any = json.loads(message_body.decode("utf-8"))

    # Accept both envelopes because Event Grid and local queue tools differ here.
    if isinstance(payload, list):
        if len(payload) != 1 or not isinstance(payload[0], dict):
            raise ValueError("Expected exactly one Event Grid event")
        payload = payload[0]

    if not isinstance(payload, dict):
        raise ValueError("Event Grid message must be a JSON object")
    return payload


def _blob_details(event: dict[str, Any]) -> tuple[str, str, str] | None:
    """Extract the container, blob name, and file ID from an event subject.

    Args:
        event: Event Grid event containing a Blob Storage subject path.

    Returns:
        Parsed storage details, or None for a non-upload or non-PDF event.

    Raises:
        ValueError: If the event subject is missing, malformed, or lacks a file ID.
    """
    subject = event.get("subject")
    if not isinstance(subject, str):
        raise ValueError("Event Grid event does not contain a valid subject")

    match = SUBJECT_PATTERN.fullmatch(subject)
    if match is None:
        raise ValueError("Event Grid subject is not a Blob Storage subject")

    container = unquote(match.group("container"))
    blob_name = unquote(match.group("blob_name"))
    if container != UPLOAD_CONTAINER or not blob_name.lower().endswith(PDF_EXTENSION):
        return None

    file_id = blob_name.partition("/")[0]
    if not file_id or "/" not in blob_name:
        raise ValueError("PDF blob name does not contain a file ID")
    return container, blob_name, file_id


def _update_status(
    table_client: TableClient,
    file_id: str,
    status_value: Status,
    **properties: Any,
) -> None:
    """Merge a lifecycle status and related properties into a Table row.

    Args:
        table_client: Shared client for the status table.
        file_id: Row key generated by the upload API.
        status_value: Lifecycle state to store.
        **properties: Additional schema properties to merge into the row.

    Returns:
        None.

    Raises:
        AzureError: If Table Storage cannot update the entity.
    """
    entity: dict[str, Any] = {
        "PartitionKey": PARTITION_KEY,
        "RowKey": file_id,
        "status": status_value.value,
        **properties,
    }
    table_client.update_entity(entity=entity, mode=UpdateMode.MERGE)


def _extract_text(pdf_content: bytes) -> str:
    """Extract text from every PDF page while tolerating textless pages.

    Args:
        pdf_content: Complete PDF document bytes downloaded from Blob Storage.

    Returns:
        Page text joined with newline separators; textless pages contribute an
        empty string.

    Raises:
        PdfReadError: If pypdf cannot parse the document.
    """
    reader = PdfReader(io.BytesIO(pdf_content))
    return "\n".join(page.extract_text() or "" for page in reader.pages)


def _short_error(error: Exception) -> str:
    """Create a bounded failure description for Table Storage.

    Args:
        error: Processing exception to summarize.

    Returns:
        Exception name and message truncated to the configured limit.

    Raises:
        None.
    """
    message = f"{type(error).__name__}: {error}"
    return message[:MAX_ERROR_LENGTH]


def _begin_processing(table_client: TableClient, file_id: str) -> bool:
    """Claim a status row with optimistic concurrency.

    Args:
        table_client: Shared client for the status table.
        file_id: Row key generated by the upload API.

    Returns:
        True after setting Processing, or False when another delivery already
        completed the file.

    Raises:
        AzureError: If Table Storage cannot read or update the entity.
        RuntimeError: If concurrent updates prevent a claim after all attempts.
    """
    for _ in range(MAX_CLAIM_ATTEMPTS):
        current = table_client.get_entity(
            partition_key=PARTITION_KEY,
            row_key=file_id,
        )
        if current.get("status") == Status.COMPLETED.value:
            return False

        entity = {
            "PartitionKey": PARTITION_KEY,
            "RowKey": file_id,
            "status": Status.PROCESSING.value,
            "error": "",
        }
        try:
            table_client.update_entity(
                entity=entity,
                mode=UpdateMode.MERGE,
                etag=current.metadata["etag"],
                match_condition=MatchConditions.IfNotModified,
            )
            return True
        except ResourceModifiedError:
            logger.info("Status row %s changed concurrently; retrying claim", file_id)

    raise RuntimeError(f"Could not claim status row {file_id} after concurrent updates")


def _mark_failed(table_client: TableClient, file_id: str, error: Exception) -> None:
    """Mark processing as failed without downgrading a completed delivery.

    Args:
        table_client: Shared client for the status table.
        file_id: Row key generated by the upload API.
        error: Processing exception summarized into the row's error property.

    Returns:
        None.

    Raises:
        AzureError: If Table Storage cannot read or conditionally update the row.
    """
    current = table_client.get_entity(
        partition_key=PARTITION_KEY,
        row_key=file_id,
    )
    if current.get("status") == Status.COMPLETED.value:
        logger.info(
            "PDF %s completed in another delivery; not changing it to Failed",
            file_id,
        )
        return

    entity = {
        "PartitionKey": PARTITION_KEY,
        "RowKey": file_id,
        "status": Status.FAILED.value,
        "error": _short_error(error),
    }
    try:
        table_client.update_entity(
            entity=entity,
            mode=UpdateMode.MERGE,
            etag=current.metadata["etag"],
            match_condition=MatchConditions.IfNotModified,
        )
    except ResourceModifiedError:
        latest = table_client.get_entity(
            partition_key=PARTITION_KEY,
            row_key=file_id,
        )
        if latest.get("status") == Status.COMPLETED.value:
            logger.info(
                "PDF %s completed in another delivery; not changing it to Failed",
                file_id,
            )
            return
        raise


STORAGE_CLIENTS = _create_storage_clients()


@app.queue_trigger(
    arg_name="message",
    queue_name="pdf-processing",
    connection=AZURE_WEBJOBS_STORAGE,
)
def process_pdf(message: func.QueueMessage) -> None:
    """Process one queued Event Grid BlobCreated event.

    Expect plain JSON containing an Event Grid event whose `subject` follows
    `/blobServices/default/containers/uploads/blobs/{file_id}/{filename}`. Ignore
    events outside the configured uploads container and non-PDF blobs. Transition
    the existing Table row from Uploaded to Processing and then to Completed after
    text upload, or to Failed before re-raising an exception for queue retry and
    poison-queue handling.

    Args:
        message: Queue message containing one Event Grid event object or a
            one-element event array.

    Returns:
        None.

    Raises:
        Exception: Re-raises parsing, storage, and PDF extraction failures after
            attempting to mark the status row as Failed.
    """
    file_id: str | None = None
    table_client = STORAGE_CLIENTS.table

    try:
        event = _parse_event(message.get_body())
        details = _blob_details(event)
        if details is None:
            logger.info("Ignoring BlobCreated event outside the PDF uploads path")
            return

        container, blob_name, file_id = details
        if not _begin_processing(table_client, file_id):
            logger.info("PDF %s is already completed; ignoring duplicate event", file_id)
            return

        source_blob = STORAGE_CLIENTS.blobs.get_blob_client(
            container=container,
            blob=blob_name,
        )
        pdf_content = source_blob.download_blob().readall()
        extracted_text = _extract_text(pdf_content)

        text_blob_name = f"{file_id}.txt"
        extracted_blob = STORAGE_CLIENTS.blobs.get_blob_client(
            container=EXTRACTED_CONTAINER,
            blob=text_blob_name,
        )
        extracted_blob.upload_blob(
            extracted_text.encode("utf-8"),
            overwrite=True,
        )

        _update_status(
            table_client,
            file_id,
            Status.COMPLETED,
            text_blob_name=text_blob_name,
            error="",
        )
        logger.info("Completed PDF processing for %s", file_id)
    except Exception as error:
        if file_id is not None:
            try:
                _mark_failed(table_client, file_id, error)
            except Exception:
                logger.exception("Could not mark PDF %s as failed", file_id)

        logger.exception("PDF processing failed for file_id=%s", file_id)
        raise
